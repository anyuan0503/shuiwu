#!/usr/bin/env bash
# =====================================================================
# 水务监测分析系统 - 一键停止 (Linux / Docker)
# 停止并移除容器(保留数据卷)，如需彻底清理数据请加 -v
# =====================================================================
set -e
cd "$(dirname "$0")"

echo "正在停止并移除 水务监测分析系统 容器 (数据卷将保留)..."
docker compose down
echo "完成。如需连数据一起删除，请运行:  docker compose down -v"